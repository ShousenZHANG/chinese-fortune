"""Freeze 《高性价比人生指南》 (eternity4719/HowToLiveBetter) into assets/life_guide.json.

Maintenance tool, excluded from the runtime package. It reads the GitHub
codeload ZIP directly and refuses any ZIP whose embedded commit is not the
pinned one, so the frozen text cannot drift from a folder edited by hand.

What is kept, verbatim: every entry's six fields and machine cost tags, each
section's intro, all long articles under docs/, and from README the question
each section answers, the four resources, the evidence grades, the
cost-effectiveness tiers and the glossary. Computed the book's way (its
index.html): the cost score and the 极高/高/一般 tier, the 争议 badge, the
待核实 flag, and every cross reference resolved to its target (its
tools/check-refs.mjs, ported in life_guide_refs.py).

Three entries are left out on purpose, by number checked against a title
fragment, as a product-scope decision: this skill does not carry the book's
verdicts on divination. The output holds no trace of them. Everything else is
kept, so the library is the whole book minus those three, not the whole book.

Regions and reviewed dispute quotes come from life_guide_review.py, keyed by
title so a renumbering upstream cannot land a review on the wrong entry.

    python scripts/import_life_guide.py --zip path/to/howtolivebetter-main.zip
"""
